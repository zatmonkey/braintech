#!/usr/bin/env node
/**
 * gen-tracker-denylist — regenerate device-agent/trackers_gen.go from
 * DuckDuckGo Tracker Radar (https://github.com/duckduckgo/tracker-radar).
 *
 * Problem: the agent classifies DNS queries into app usage by domain
 * suffix ("*.snapchat.com" → Snapchat). Ad/analytics pixels live on
 * subdomains of those same zones (tr.snapchat.com = Snap Pixel), so a
 * web page running Snap ads reads as "kid is on Snapchat".
 *
 * Source of truth: Tracker Radar's per-domain JSON lists the subdomains
 * observed loading as a THIRD PARTY on other sites — exactly the pixel/
 * beacon population. But it also contains dual-use hosts (www.facebook.com
 * serves both Like buttons and the actual site), so we only deny a
 * radar-observed subdomain when its NAME also looks tracker-ish
 * (tr/pixel/analytics/events/...). False negatives are cheap (a missed
 * pixel slightly inflates usage); false positives erase real usage —
 * so this errs toward keeping.
 *
 * Zones are parsed from appDomains in device-agent/usage.go, so adding an
 * app there and re-running this keeps the two in sync.
 *
 * Usage: node scripts/gen-tracker-denylist.mjs   (then rebuild the agent)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const USAGE_GO = join(ROOT, "device-agent", "usage.go");
const OUT_GO = join(ROOT, "device-agent", "trackers_gen.go");
const RADAR_BASE =
  "https://raw.githubusercontent.com/duckduckgo/tracker-radar/main/domains/US";

// Subdomain names that denote tracking/ads/analytics. Anchored full-label
// matches for the short cryptic ones; substring for the descriptive ones.
const TRACKER_EXACT = new Set([
  "tr", "tr6", "intg", // Snap Pixel family
  "pi", "px", "ct", "alb", // reddit/pinterest pixel ingest, ad load balancer
  "ads", "adserver", "adsapi", "ads-api", "business-api",
  "log", "logs", "spade", // twitch's own analytics collector
  "fcmatch", // Google floodlight conversion matching
]);
const TRACKER_SUBSTR = [
  "pixel", "analytics", "track", "beacon", "telemetr", "metric",
  "event", "collect", "conversion", "measure", "adlog", "audit",
];

// Dual-use hosts that must NEVER be denied even if radar saw them
// third-party: embeds and API hosts count as real usage.
const DUAL_USE = new Set([
  "www", "api", "graph", "web", "m", "mobile", "app", "embed", "player",
  "platform", "assets", "static", "cdn", "media", "img", "images", "video",
  "gql", "chat", "accounts", "login", "auth", "open", "badges", "badge",
]);

function isTrackerName(sub) {
  const leaf = sub.split(".")[0]; // "irc-ws.chat" → judge "irc-ws"
  if (DUAL_USE.has(sub) || DUAL_USE.has(leaf)) return false;
  if (TRACKER_EXACT.has(sub) || TRACKER_EXACT.has(leaf)) return true;
  return TRACKER_SUBSTR.some((t) => sub.includes(t));
}

function parseZones(goSrc) {
  const block = goSrc.match(/var appDomains = map\[string\]string\{([\s\S]*?)\n\}/);
  if (!block) throw new Error("appDomains map not found in usage.go");
  const zones = [...block[1].matchAll(/"([a-z0-9][a-z0-9.-]*\.[a-z]{2,})":/g)].map(
    (m) => m[1],
  );
  if (zones.length === 0) throw new Error("no zones parsed from appDomains");
  return [...new Set(zones)];
}

async function radarSubdomains(zone) {
  const res = await fetch(`${RADAR_BASE}/${zone}.json`);
  if (res.status === 404) return null; // never seen third-party — nothing to deny
  if (!res.ok) throw new Error(`radar fetch ${zone}: HTTP ${res.status}`);
  const doc = await res.json();
  return { subdomains: doc.subdomains ?? [], categories: doc.categories ?? [] };
}

const zones = parseZones(readFileSync(USAGE_GO, "utf8"));
const denied = []; // { fqdn, zone }
const skipped = [];
for (const zone of zones) {
  const radar = await radarSubdomains(zone);
  if (!radar) {
    skipped.push(zone);
    continue;
  }
  for (const sub of radar.subdomains) {
    if (isTrackerName(sub)) denied.push({ fqdn: `${sub}.${zone}`, zone });
  }
}
denied.sort((a, b) => a.fqdn.localeCompare(b.fqdn));

const stamp = new Date().toISOString().slice(0, 10);
const lines = [
  "package main",
  "",
  "// Code generated by scripts/gen-tracker-denylist.mjs — DO NOT EDIT BY HAND.",
  `// Source: DuckDuckGo Tracker Radar (${RADAR_BASE}), generated ${stamp}.`,
  "// Re-run the script to refresh; see its header for the selection rules.",
  "//",
  "// Ad/analytics/pixel hosts living inside app zones the usage classifier",
  "// attributes (tr.snapchat.com etc). A DNS query to one of these means",
  '// "a web page is phoning home to this company\'s ad system", not "the',
  '// kid is using this app" — so classifyApp and the quota recorders skip',
  "// them.",
  "var trackerDomains = map[string]bool{",
  ...denied.map((d) => `\t"${d.fqdn}": true, // in ${d.zone} zone`),
  "}",
  "",
  "// isTrackerDomain reports whether the queried name is (or is under) a",
  "// known tracking endpoint. Same suffix semantics as matchesAny.",
  "func isTrackerDomain(domain string) bool {",
  "\td := normalizeDomain(domain)",
  "\tif trackerDomains[d] {",
  "\t\treturn true",
  "\t}",
  "\tfor t := range trackerDomains {",
  '\t\tif len(d) > len(t) && d[len(d)-len(t)-1] == \'.\' && d[len(d)-len(t):] == t {',
  "\t\t\treturn true",
  "\t\t}",
  "\t}",
  "\treturn false",
  "}",
  "",
];
writeFileSync(OUT_GO, lines.join("\n"));
console.log(`zones: ${zones.length} (${skipped.length} with no radar file: ${skipped.join(", ") || "—"})`);
console.log(`denied ${denied.length} tracker hosts → ${OUT_GO}`);
for (const d of denied) console.log(`  ${d.fqdn}`);
